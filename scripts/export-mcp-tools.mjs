// Writes docs/mcp-tools.json:  the MCP tools FleetLink serves (names, argument
// names, required arguments).  The Agent-Sync MCP pins its FleetLink tools to
// this file;  test/cli-mcp-parity.test.mjs fails when it is stale.
import { writeFileSync } from "node:fs";
import { z } from "zod";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { callJson, createToken, makeEnv, signUp } from "../test/helpers/harness.mjs";

const repo = dirname(dirname(fileURLToPath(import.meta.url)));
const env = await makeEnv();
const ada = await signUp(env, "Export");
const token = await createToken(env, ada);
const res = await callJson(env, "POST", "/mcp", { auth: { token }, json: { jsonrpc: "2.0", id: 1, method: "tools/list", params: {} } });
// Parse the tools/list answer before anything from it is written to disk.
const ToolsList = z.object({
  result: z.object({
    tools: z.array(z.object({
      name: z.string().regex(/^fleetlink_[a-z_]+$/),
      inputSchema: z.object({ properties: z.record(z.string(), z.unknown()).optional(), required: z.array(z.string()).optional() }).passthrough()
    }).passthrough()).min(1)
  }).passthrough()
}).passthrough();
const parsed = ToolsList.parse(res.data);
const tools = parsed.result.tools.map(({ name, inputSchema }) => ({ name, properties: Object.keys(inputSchema.properties ?? {}).sort(), required: inputSchema.required ?? [] }));
writeFileSync(join(repo, "docs/mcp-tools.json"), `${JSON.stringify({ note: "Generated by scripts/export-mcp-tools.mjs.  Do not edit by hand.", tools }, null, 2)}\n`);
console.log(`wrote ${tools.length} tools`);
