#!/usr/bin/env python3
"""Build the website logo, favicon, and touch icon from the iOS app icon.

Reads ios/Assets.xcassets/AppIcon.appiconset/icon-1024.png, crops to the mark,
and writes assets/web/*.png plus worker/lib/pages/brand-data.mjs, which the
worker serves from /assets and /favicon.ico.  Needs Pillow.  Run it again
whenever the app icon changes:

    python3 scripts/build-brand.py
"""
import base64
import io
import os

from PIL import Image, ImageChops, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "ios/Assets.xcassets/AppIcon.appiconset/icon-1024.png")
WEB = os.path.join(ROOT, "assets/web")
MODULE = os.path.join(ROOT, "worker/lib/pages/brand-data.mjs")


def crop_to_mark(image):
    """Square crop around everything that is not the white background, with a small margin."""
    white = Image.new("RGB", image.size, (255, 255, 255))
    mask = ImageChops.difference(image, white).convert("L").point(lambda p: 255 if p > 24 else 0)
    left, top, right, bottom = mask.getbbox()
    cx, cy = (left + right) / 2, (top + bottom) / 2
    side = max(right - left, bottom - top) * 1.08
    return image.crop((int(cx - side / 2), int(cy - side / 2), int(cx + side / 2), int(cy + side / 2)))


def rounded(image, ratio=0.22):
    size = image.size[0]
    big = Image.new("L", (size * 4, size * 4), 0)
    ImageDraw.Draw(big).rounded_rectangle((0, 0, size * 4 - 1, size * 4 - 1), radius=int(size * 4 * ratio), fill=255)
    out = image.convert("RGBA")
    out.putalpha(big.resize((size, size), Image.LANCZOS))
    return out


def png(image):
    buf = io.BytesIO()
    image.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def browser_touch_icon():
    # Apple touch icons must be opaque; iOS applies its own rounding.
    source = Image.open(os.path.join(WEB, "favicon-light-512.png")).convert("RGBA")
    canvas = Image.new("RGBA", source.size, "white")
    canvas.alpha_composite(source)
    return canvas.convert("RGB").resize((180, 180), Image.LANCZOS)


def main():
    mark = crop_to_mark(Image.open(SOURCE).convert("RGB"))
    files = {
        "logo-64.png": png(rounded(mark.resize((64, 64), Image.LANCZOS))),
        "logo-128.png": png(rounded(mark.resize((128, 128), Image.LANCZOS))),
        # Browser icons use the existing standalone mark, never the boxed app icon.
        "apple-touch-icon.png": png(browser_touch_icon()),
    }
    ico = io.BytesIO()
    browser_mark = Image.open(os.path.join(WEB, "favicon-light-512.png")).convert("RGBA")
    browser_mark.save(ico, "ICO", sizes=[(16, 16), (32, 32), (48, 48)])
    files["favicon.ico"] = ico.getvalue()

    os.makedirs(WEB, exist_ok=True)
    for name, data in files.items():
        with open(os.path.join(WEB, name), "wb") as handle:
            handle.write(data)

    # Owner-supplied standalone art is embedded without regenerating it.
    for extra in ("fleetlink-wordmark.png", "fleetlink-wordmark.webp", "favicon-light-512.png", "favicon-dark-512.png"):
        path = os.path.join(WEB, extra)
        if os.path.isfile(path):
            with open(path, "rb") as handle:
                files[extra] = handle.read()

    lines = [
        "// Generated by scripts/build-brand.py from the iOS app icon.  Do not edit by hand.",
        "export const BRAND_FILES = {",
    ]
    types = {".png": "image/png", ".ico": "image/x-icon", ".webp": "image/webp"}
    for name, data in files.items():
        kind = types[os.path.splitext(name)[1]]
        lines.append(f'  "{name}": {{ type: "{kind}", base64: "{base64.b64encode(data).decode()}" }},')
    lines.append("};")
    with open(MODULE, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    for name, data in files.items():
        print(f"{name}: {len(data)} bytes")


if __name__ == "__main__":
    main()
